#!/usr/bin/env bash
# Builds web-ready assets from the untouched Figma exports in figma-assets/.
# Re-run after re-exporting anything from Figma.
#
# Needs: cwebp (brew install webp), python3 with fonttools + brotli
# (pip3 install fonttools brotli), and the Pragmatica fonts in ~/Library/Fonts.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/figma-assets"
IMG="$ROOT/assets/img"
FONTS="$ROOT/assets/fonts"
FONT_SRC="${FONT_SRC:-$HOME/Library/Fonts}"

mkdir -p "$IMG" "$FONTS"

# webp <source> <output-name> <width>...
webp() {
  local src="$1" name="$2"; shift 2
  for w in "$@"; do
    cwebp -quiet -q 82 -m 6 -resize "$w" 0 "$SRC/$src" -o "$IMG/$name-$w.webp"
  done
}

# Hero model: Figma "Mask group" 37:15. The photo (37:2, a 1957 x 2934 box at
# frame x 115, y -642) is clipped to Rectangle 22 (1339 x 1596 at 292, 196) and
# faded by Rectangle 21's gradient (rect at y 159; opaque to 31.94% of 1597px,
# transparent at 100%). Figma's PNG export flattens transparency onto grey, so
# the masks are applied here instead, at the photo's native resolution.
TMP="$(mktemp -d)"
python3 - "$SRC/hero-model-photo.png" "$TMP/hero-model.png" <<'PY'
import sys
import numpy as np
from PIL import Image
src, out = sys.argv[1], sys.argv[2]
photo = Image.open(src).convert("RGBA")
sx, sy = photo.width / 1957, photo.height / 2934           # source px per design px
box = (177 * sx, 838 * sy, (177 + 1339) * sx, (838 + 1596) * sy)  # Rectangle 22 in photo px
w, h = round(1339 * sx), round(1596 * sy)
crop = photo.transform((w, h), Image.EXTENT, box, Image.BICUBIC)
y = (np.arange(h) + 0.5) / h * 1596 + (196 - 159)          # design px from Rectangle 21's top
t = y / 1597
fade = np.clip(1 - (t - 0.319387) / (1 - 0.319387), 0, 1)
rgba = np.asarray(crop).astype(np.float32)
rgba[..., 3] *= fade[:, None]
Image.fromarray(rgba.round().astype(np.uint8), "RGBA").save(out)
print(f"hero-model.png {w} x {h}")
PY
for w in 1000 1869; do
  cwebp -quiet -q 82 -m 6 -alpha_q 100 -resize "$w" 0 "$TMP/hero-model.png" -o "$IMG/hero-model-$w.webp"
done
rm -rf "$TMP"
webp track-photo.jpg   track-photo   800 1400 2305
webp bottle-side.png   bottle-side   800 1400 2800
webp bottle-front.png  bottle-front  500 900 1539
webp prize-hyrox.png   prize-hyrox   600 1100
webp prize-actiph.png  prize-actiph  400 800
webp prize-airpods.png prize-airpods 500 768
webp actiph-logo.png   actiph-logo   420 640

cp "$SRC"/*.svg "$IMG/"
rm -f "$IMG"/hero-model-mask-*.svg   # reference copies of Figma's masks; applied above

# Latin + Latin Extended-A (covers Maltese ċ ġ ħ ż) and common punctuation.
UNICODES="U+0000-017F,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD"

for f in Pragmatica-Light Pragmatica-Book Pragmatica-Bold Pragmatica-Black Pragmatica-MediumOblique \
         PragmaticaExtended-Bold PragmaticaExtended-BlackOblique; do
  python3 -m fontTools.subset "$FONT_SRC/$f.ttf" --unicodes="$UNICODES" \
    --layout-features='*' --flavor=woff2 --output-file="$FONTS/$f.woff2"
done

# Browsers block font files on pages opened straight from disk (file://), so
# index.html loads this inlined copy only in that case. Keep in sync with the
# @font-face rules at the top of assets/css/styles.css.
python3 - "$FONTS" "$ROOT/assets/css/fonts-inline.css" <<'PY'
import base64, sys
fonts_dir, out = sys.argv[1], sys.argv[2]
faces = [
    ("Pragmatica", "Pragmatica-Light", 300, "normal"),
    ("Pragmatica", "Pragmatica-Book", 400, "normal"),
    ("Pragmatica", "Pragmatica-MediumOblique", 500, "italic"),
    ("Pragmatica", "Pragmatica-Bold", 700, "normal"),
    ("Pragmatica", "Pragmatica-Black", 900, "normal"),
    ("Pragmatica Extended", "PragmaticaExtended-Bold", 700, "normal"),
    ("Pragmatica Extended", "PragmaticaExtended-BlackOblique", 900, "italic"),
]
with open(out, "w") as f:
    f.write("/* Generated by scripts/build-assets.sh: only used when the page is opened from disk. */\n")
    for family, name, weight, style in faces:
        data = base64.b64encode(open(f"{fonts_dir}/{name}.woff2", "rb").read()).decode()
        f.write(f'@font-face {{ font-family: "{family}"; src: url(data:font/woff2;base64,{data}) format("woff2"); '
                f"font-weight: {weight}; font-style: {style}; }}\n")
PY

echo "Assets built:"
du -sh "$IMG" "$FONTS"
